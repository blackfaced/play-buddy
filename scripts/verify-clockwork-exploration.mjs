import assert from 'node:assert/strict';
import {build} from 'esbuild';
await build({entryPoints:['src/escape/campaign/episodes/clockworkLogic.ts'],outfile:'node_modules/.tmp-clockwork-exploration.mjs',bundle:true,platform:'node',format:'esm'});
const M=await import('../node_modules/.tmp-clockwork-exploration.mjs');
const start=M.initialClockwork();
assert.deepEqual(start.values.gears,[0,0,0],'new game begins with empty axles');
assert.deepEqual(start.values.foundGears,[]);
assert.equal(start.values.explorationVersion,3);
assert.deepEqual(M.placeClockworkGear([0,0,0],24,1),[0,24,0]);
assert.deepEqual(M.placeClockworkGear([24,36,48],24,2),[48,36,24]);
assert.deepEqual(M.placeClockworkGear([24,36,0],24,-1),[0,36,0]);
assert.deepEqual(M.normalizeClockwork({...start,values:{...start.values,gears:[24,24,48],foundGears:[24]}}).values.gears,[24,0,0]);
const legacy={values:{gears:[24,36,48],mural:[0,3,2,1],cams:[9,6,8],crank:2,cloth:true,released:true},solved:['gears','mural'],inventory:[],inspected:[]};
const migrated=M.normalizeClockwork(legacy);
assert.equal(migrated.values.released,true);
assert.equal(migrated.values.upperOpen,true);
assert.deepEqual(migrated.values.foundGears,[24,36,48]);
assert.deepEqual(M.normalizeClockwork(migrated),migrated);
console.log('Clockwork exploration state, mount/swap/remove and legacy completion migration pass.');
