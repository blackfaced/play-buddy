import assert from 'node:assert/strict';
import { deriveLinkedAnswers } from './verify-escape-chapter-reasoning.mjs';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';
import postcss from 'postcss';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { create, act } from 'react-test-renderer';
await build({stdin:{contents:`export {default as PuzzleView} from './src/escape/chapter/PuzzleView';export * from './src/escape/chapter/content';`,resolveDir:process.cwd()},outfile:'node_modules/.tmp-clue-legibility.mjs',bundle:true,platform:'node',format:'esm',jsx:'automatic',packages:'external'});
const A=await import(process.cwd()+'/node_modules/.tmp-clue-legibility.mjs');
const puzzle=A.CHAPTER.puzzles.find(p=>p.id==='pattern-tray');
const progress={input:{kind:'arrangement',slots:deriveLinkedAnswers(A.CHAPTER).pattern},solved:false,undo:[],redo:[],hints:0};
const css=readFileSync('src/escape/chapter/chapter.css','utf8');
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
let tree; const actions=[];
await act(()=>{tree=create(React.createElement(A.PuzzleView,{puzzle,progress,mode:'challenge',onAction:a=>actions.push(a)}));});
const cells=tree.root.findAllByProps({className:'chapter-pattern-cell'});
assert.equal(cells.length,puzzle.slots.length);
for(const cell of cells) assert.equal(cell.findAllByType('button').length,1,'A physical clue cell must never contain an overlapping removal control');
await act(()=>cells[0].findByType('button').props.onClick());
const toolbar=tree.root.findByProps({'aria-label':'纹片操作'});
assert.ok(!cells.some(c=>c.findAllByProps({'aria-label':'纹片操作'}).length),'Removal toolbar stays outside the board');
assert.equal(actions.length,0,'Selecting a placed tile does not change the puzzle');
assert.equal(cells[0].findByType('button').props['aria-pressed'],true);
const hostElement=node=>typeof node==='string'?node:React.createElement(node.type,node.props,...(node.children??[]).map(hostElement));
const editingHtml=renderToStaticMarkup(hostElement(tree.toJSON()));
await act(()=>toolbar.findByType('button').props.onClick());
assert.equal(actions.at(-1).input.slots[0],null,'Contextual removal keeps the original state action');
const solved={...progress,solved:true};
const sudoku=A.CHAPTER.puzzles.find(p=>p.kind==='sudoku');
const sudokuHtml=renderToStaticMarkup(React.createElement(A.PuzzleView,{puzzle:sudoku,progress:{...solved,input:{kind:'sudoku',cells:deriveLinkedAnswers(A.CHAPTER).sudoku}},mode:'challenge',onAction(){}}));
assert.ok(!sudokuHtml.includes('chapter-number-pad'),'Solved sudoku omits disabled input controls');
assert.ok(!sudokuHtml.includes(' selected'),'Solved sudoku has no stale edit selection');
const html=renderToStaticMarkup(React.createElement(A.PuzzleView,{puzzle,progress:solved,mode:'challenge',onAction(){}}));
assert.ok(!html.includes('chapter-remove'),'Completed boards have no removal buttons');
assert.ok(!html.includes('chapter-piece-tray'),'Completed boards have no disabled edit tray');
assert.ok(html.includes('disabled=""'),'Completion still locks changes');
assert.equal((html.match(/data-emblem=/g)||[]).length,6,'All six full-component physical emblems stay present');
const rules=postcss.parse(css);
for(const selector of ['.chapter-puzzle .chapter-slot:disabled','.chapter-puzzle .chapter-sudoku button:disabled','.chapter-puzzle input:disabled']) {
 let opacity;
 rules.walkRules(rule=>{if(rule.selectors.includes(selector)) rule.walkDecls('opacity',decl=>{opacity=decl.value;});});
 assert.equal(opacity,'1',`${selector} preserves physical evidence at full opacity`);
}
const art=readFileSync('src/escape/chapter/PatternArt.tsx','utf8');
for(const ink of ['#915733','#435e65','#695336']) assert.ok(art.includes(ink),'Contrast checks cover actual SVG ink');
assert.ok(!/\.chapter-pattern-cell \.chapter-remove\s*\{[^}]*position:\s*absolute/.test(css),'No overlay rule remains');
const luminance=hex=>{const v=hex.match(/\w\w/g).map(n=>parseInt(n,16)/255).map(n=>n<=.04045?n/12.92:((n+.055)/1.055)**2.4);return .2126*v[0]+.7152*v[1]+.0722*v[2];};
const contrast=(a,b)=>{const l=[luminance(a),luminance(b)].sort((x,y)=>y-x);return(l[0]+.05)/(l[1]+.05);};
for(const bg of ['f5e6c3','e8d4a8','d0ba90']) for(const ink of ['915733','435e65','695336']) assert.ok(contrast(ink,bg)>=3,`${ink} on ${bg} must meet non-text clue contrast`);
assert.ok(contrast('f7deb1','284448')>=4.5,'Sudoku digits retain text contrast');
mkdirSync('node_modules/.tmp-clue-evidence',{recursive:true});
writeFileSync('node_modules/.tmp-clue-evidence/editing-pattern.html',`<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style><main class="chapter-dialog">${editingHtml}</main>`);
writeFileSync('node_modules/.tmp-clue-evidence/solved-pattern.html',`<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style><main class="chapter-dialog">${html}</main>`);
await act(()=>tree.unmount());
console.log('Full PuzzleView clue visibility, contextual removal, completion lock, and contrast checks passed');
