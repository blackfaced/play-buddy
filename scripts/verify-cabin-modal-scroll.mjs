import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';
import React from 'react';
import { create, act } from 'react-test-renderer';
import { MemoryRouter } from 'react-router';

await build({ stdin: { contents: `export {default as EscapeRoom} from './src/escape/EscapeRoom';`, resolveDir: process.cwd() }, outfile: 'node_modules/.tmp-cabin-modal-scroll.mjs', bundle: true, platform: 'node', format: 'esm', packages: 'external', jsx: 'automatic', loader: { '.css': 'empty' }, plugins: [{ name: 'health-double', setup(b) { b.onResolve({ filter: /store\/useStore$/ }, () => ({ path: 'store', namespace: 'test' })); b.onLoad({ filter: /.*/, namespace: 'test' }, () => ({ contents: 'export const useStore = f => f({lock:globalThis.__modalLock ?? null});' })); } }] });
const { EscapeRoom } = await import('../node_modules/.tmp-cabin-modal-scroll.mjs');
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const storage = new Map();
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v) };
globalThis.document = { body: { style: { overflow: 'auto' } }, documentElement: { style: { overflow: 'scroll' } } };
const original = () => { assert.equal(document.body.style.overflow, 'auto'); assert.equal(document.documentElement.style.overflow, 'scroll'); };
const locked = () => { assert.equal(document.body.style.overflow, 'hidden'); assert.equal(document.documentElement.style.overflow, 'hidden'); };
let tree, opens = 0, closes = 0;
const wrap = () => React.createElement(React.StrictMode, null, React.createElement(MemoryRouter, null, React.createElement(EscapeRoom)));
await act(async () => { tree = create(wrap(), { createNodeMock: el => el.type === 'dialog' ? { showModal() { opens++; }, close() { closes++; } } : null }); });
locked();
const close = () => tree.root.findByProps({ 'aria-label': '关闭近景' });
const text = n => typeof n === 'string' ? n : (n.children ?? []).map(text).join('');
const reopen = async () => act(async () => tree.root.findAllByType('button').find(b => text(b) === '航海手记').props.onClick());
await act(async () => close().props.onClick()); original();
await reopen(); locked();
await act(async () => tree.root.findByType('dialog').props.onCancel()); original();
await reopen(); locked();
await act(async () => { const dialog = tree.root.findByType('dialog'); dialog.props.onClick({ target: dialog, currentTarget: dialog }); }); original();
await reopen(); locked();
await act(async () => { globalThis.__modalLock = 'daily'; tree.update(wrap()); }); original();
await act(async () => { globalThis.__modalLock = null; tree.update(wrap()); }); locked();
await act(async () => tree.unmount()); original();
assert.equal(opens, closes, 'every modal effect, including StrictMode replay, closes and cleans up');
const css = readFileSync('src/escape/escape.css', 'utf8');
assert.match(css, /\.escape-modal\s*\{[^}]*overscroll-behavior:\s*contain/s);
assert.match(css, /\.escape-ring-workarea\s*\{[^}]*grid-template-columns:\s*250px\s+minmax\(0,\s*1fr\)/s);
assert.match(css, /@media\s*\(max-width:\s*650px\)[\s\S]*\.escape-ring-workarea\s*\{[^}]*grid-template-columns:\s*1fr/s);
assert.match(css, /\.escape-ring-dialog\s+\.escape-modal-status\s*\{[^}]*margin-top:\s*12px\s*!important/s);
console.log('Cabin modal: StrictMode, close, Escape, health-lock and unmount restore page scrolling; desktop/mobile ring layout boundaries pass. Pixel layout needs browser verification.');
