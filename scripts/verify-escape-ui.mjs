/** Headless React interaction checks; no browser/server/network is needed. */
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import React from 'react';
import { create, act } from 'react-test-renderer';
import { MemoryRouter } from 'react-router';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const outfile = path.resolve('node_modules/.tmp-escape-ui.mjs');
await build({ stdin: { contents: `export { default as EscapeRoom } from './src/escape/EscapeRoom'; export * from './src/escape/logic'; export * from './src/escape/guidancePolicy';`, resolveDir: process.cwd() }, outfile, bundle: true, platform: 'node', jsx: 'automatic', format: 'esm', packages: 'external', loader: { '.css': 'empty' }, plugins: [{ name: 'health-store-test-double', setup(b) { b.onResolve({ filter: /store\/useStore$/ }, () => ({ path: 'store', namespace: 'test' })); b.onLoad({ filter: /.*/, namespace: 'test' }, () => ({ contents: 'export const useStore = selector => selector({lock:globalThis.__escapeTestLock ?? null});' })); } }] });
const { EscapeRoom, initialState, serializeSave, parseSave, SAVE_KEY, MODE_KEY } = await import(pathToFileURL(outfile));
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const storage = new Map();
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,v) };
const seed = { ...initialState(), cloth: true, seen: ['flags'] };
storage.set(SAVE_KEY, serializeSave(seed));
let tree;
const wrap = props => React.createElement(MemoryRouter, null, React.createElement(EscapeRoom, props));
await act(async () => { tree = create(wrap({}), { createNodeMock: el => el.type === 'dialog' ? { showModal() {} } : null }); });
const text = () => JSON.stringify(tree.toJSON());
const byLabel = label => tree.root.findByProps({ 'aria-label': label });
const click = async button => { await act(async () => button.props.onClick()); };
const nodeText = n => typeof n === 'string' ? n : (n.children ?? []).map(nodeText).join('');
const buttonText = label => { const b = tree.root.findAllByType('button').find(b => nodeText(b).trim() === label.trim()); assert.ok(b, `Missing button: ${label}`); return b; };
const changeMode = async value => { await act(async () => tree.root.findByType('select').props.onChange({ target: { value } })); };
assert.equal(tree.root.findByType('select').props.value, 'standard');
await click(byLabel('检查递推算图'));
assert.ok(!text().includes('左上方'));
const scratch = byLabel('第2行第2格，星');
await act(async () => scratch.props.onChange({ target: { value: '9' } }));
await click(byLabel('关闭近景'));
await click(buttonText('航海手记'));
assert.equal(byLabel('第2行第2格，星').props.value, '9');
assert.ok(!text().includes('左上方'));
await click(byLabel('关闭近景'));
await changeMode('easy');
await click(byLabel('检查递推算图'));
assert.ok(text().includes('左上方'));
await click(byLabel('关闭近景'));
await changeMode('standard');
await click(buttonText(' 来点提示'));
assert.ok(!text().includes('密码 375'));
await click(buttonText('解释规律'));
assert.ok(text().includes('左上方'));
assert.ok(!text().includes('密码 375'));
await click(buttonText('揭晓答案（含完整解法）'));
assert.ok(text().includes('密码 375'));
// A mode change from an enclosing adventure must dismiss even an already-open answer.
await act(async () => tree.update(wrap({ mode: 'challenge' })));
assert.equal(tree.root.findAllByType('dialog').length, 0);
assert.ok(!text().includes('来点提示'));
assert.equal(tree.root.findAllByProps({ className: 'escape-hotspot unmarked' }).length, 2);
await act(async () => tree.update(wrap({ mode: 'standard' })));
assert.equal(tree.root.findAllByType('dialog').length, 0);
await click(byLabel('检查递推算图'));
assert.equal(byLabel('第2行第2格，星').props.value, '9');
assert.ok(!text().includes('左上方'));
await click(byLabel('关闭近景'));
assert.deepEqual(parseSave(storage.get(SAVE_KEY)), seed);
// Reversible placement: a wrong piece still lands; no correctness shown until final confirm.
await click(byLabel('向右转')); await click(byLabel('向右转'));
await click(byLabel('检查木条画'));
await click(byLabel('木条 2、4、6、？'));
await click(byLabel('槽位 12，空槽'));
assert.ok(byLabel('槽位 12，木条 2、4、6，点击拿下'));
assert.equal(buttonText('确认整幅画').props.disabled, true);
assert.ok(!text().includes('木条没有嵌合'));
await click(byLabel('槽位 12，木条 2、4、6，点击拿下'));
assert.ok(byLabel('木条 2、4、6、？'));
for (const [piece, slot] of [['2、4、6',12],['3、6、9',8],['1、6、11',16],['1、4、7',10],['2、6、10',14]]) {
  await click(byLabel(`木条 ${piece}、？`)); await click(byLabel(`槽位 ${slot}，空槽`));
}
assert.equal(buttonText('确认整幅画').props.disabled, false);
assert.equal(parseSave(storage.get(SAVE_KEY)).picture, false);
const wrong = storage.get(SAVE_KEY);
await click(buttonText('确认整幅画'));
assert.equal(storage.get(SAVE_KEY), wrong);
assert.ok(text().includes('整幅画还没有吻合'));
await click(byLabel('关闭近景'));
await changeMode('challenge');
assert.equal(storage.get(MODE_KEY), 'challenge');
assert.equal(storage.get(SAVE_KEY), wrong);
// Health lock still suppresses dialogs and makes the entire cabin inert.
globalThis.__escapeTestLock = 'rest';
await act(async () => tree.update(wrap({ mode: 'challenge' })));
assert.equal(tree.root.findByType('main').props.inert, true);
assert.equal(tree.root.findAllByType('dialog').length, 0);
await act(async () => tree.unmount());
console.log('Escape React interactions verified: notebook, scratch preservation, progressive consent, stale-modal transitions, wood placement/removal/confirmation, saves and HealthGate.');
