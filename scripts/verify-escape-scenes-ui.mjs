import assert from 'node:assert/strict';
import { build } from 'esbuild';
import React from 'react';
import { create, act } from 'react-test-renderer';
import { MemoryRouter, useNavigate, useLocation } from 'react-router';
await build({ stdin: { contents: `export { default as SceneSelect } from './src/escape/SceneSelect'; export * from './src/escape/logic'; export * from './src/escape/adventure/logic'; export * from './src/escape/scenes'; export * from './src/escape/chapter/content'; export * from './src/escape/chapter/engine';`, resolveDir: process.cwd() }, outfile:'node_modules/.tmp-scenes-ui.mjs', bundle:true, platform:'node', format:'esm', packages:'external', jsx:'automatic', loader:{'.css':'empty'}, plugins:[{name:'health-double',setup(b){b.onResolve({filter:/store\/useStore$/},()=>({path:'store',namespace:'test'}));b.onLoad({filter:/.*/,namespace:'test'},()=>({contents:'export const useStore = fn => fn({lock: globalThis.__sceneLock ?? null});'}));}}] });
const A = await import('../node_modules/.tmp-scenes-ui.mjs');
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const storage = new Map();
globalThis.localStorage = {getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v)};
let tree, navigate, path;
function History(){navigate=useNavigate();path=useLocation();return null;}
const wrap = (route='/escape') => React.createElement(MemoryRouter,{initialEntries:[route]},React.createElement(History),React.createElement(A.SceneSelect));
const mount = async (route) => { await act(async()=>{ tree=create(wrap(route),{createNodeMock:e=>e.type==='dialog'?{showModal(){},close(){}}:null}); }); };
const unmount = async()=>act(async()=>tree.unmount());
const text = n=>typeof n==='string'?n:(n.children??[]).map(text).join('');
const button = title=>{const result=tree.root.findAllByType('button').find(n=>text(n).trim()===title||n.props['aria-label']===title);assert.ok(result,'missing '+title);return result;};
const click = async title=>{const b=button(title);assert.ok(!b.props.disabled);await act(async()=>b.props.onClick());};
await mount();
assert.equal(button('未解锁海风里的星光').props.disabled,true);
assert.equal(button('未解锁雾灯工坊').props.disabled,true);
assert.equal(storage.has(A.SAVE_KEY),false,'Landing never initializes or resets episode saves');
await click('进入航海员的钥匙');
assert.equal(path.search,'?scene=cabin');
await act(async()=>navigate(-1));
assert.ok(button('进入航海员的钥匙'));
await unmount();
await mount('/escape?scene=foglight');
assert.ok(text(tree.toJSON()).includes('暂未解锁'));
assert.equal(storage.has(A.CHAPTER_KEY),false,'Locked deep link cannot overwrite chapter');
await unmount();
// A completed first episode can be revisited spatially without clearing anything.
const cabin={...A.initialState(), picture:true, slats:[0,1,2,3,4], cloth:true, chart:true, drawer:true, cabinet:true, combined:true, token2:true, tokensInserted:true, rings:[0,0,0], safe:true, escaped:true, seen:[]};
storage.set(A.SAVE_KEY,A.serializeSave(cabin));
const cabinRaw=storage.get(A.SAVE_KEY);
await mount();
await click('进入航海员的钥匙');
await click('回船舱看看');
assert.ok(tree.root.findAllByProps({'aria-label':'船舱视角'}).length);
assert.equal(storage.get(A.SAVE_KEY),cabinRaw);
await click('场景选择');
assert.ok(button('进入海风里的星光'));
await click('进入航海员的钥匙');
await click('再航行一次');
await click('确认重新开始');
await click('关闭近景');
await click('场景选择');
assert.equal(button('进入海风里的星光').props.disabled,false);
await unmount();
const adventure={...A.initialAdventure(),started:true,room:'navigation',compassCaseOpen:true,manifestMoved:true,canvasLifted:true,found:[...A.ITEMS],storeroomOpen:true,ledgerClean:true,safeOpen:true,batteryMounted:true,lensMounted:true,cardMounted:true,projectorOn:true,cells:[...A.ANCHOR],panelOpen:true,crankMounted:true,hookMounted:true,gangwayDown:true,complete:true};
const savedAdventure=A.serializeAdventure(adventure);
storage.set(A.ADVENTURE_KEY,savedAdventure);
storage.delete(A.SCENES_KEY);
await mount();
assert.ok(button('进入雾灯工坊'));
assert.equal(storage.get(A.ADVENTURE_KEY),savedAdventure,'Legacy menu migration never changes saves');
await click('进入雾灯工坊');
assert.ok(text(tree.toJSON()).includes('归航之光'));
await click('← 场景选择');
assert.equal(path.search,'');
assert.equal(storage.get(A.ADVENTURE_KEY),savedAdventure,'Chapter return never travels through deck');
await click('进入海风里的星光');
assert.ok(text(tree.toJSON()).includes('导航室'));
assert.equal(storage.get(A.ADVENTURE_KEY),savedAdventure,'Completed revisit preserves current room and all items');
assert.equal(tree.root.findAllByType('button').filter(n=>text(n)==='← 船舱').length,0,'Episodes are not a room-navigation prerequisite');
await click('重新探索');
await click('确认重新探索后两间房');
await click('← 场景选择');
assert.equal(button('进入雾灯工坊').props.disabled,false,'Resetting prior chapter never revokes unlock');
globalThis.__sceneLock='rest';
await act(async()=>tree.update(wrap()));
assert.equal(tree.root.findByType('main').props.inert,true);
await act(async()=>button('进入雾灯工坊').props.onClick());
assert.equal(path.search,'','HealthGate also guards direct click handlers');
globalThis.__sceneLock=null;
await unmount();
// A valid chapter in progress remains directly accessible even if old episode saves were removed.
storage.clear();
let chapter=A.reduceChapter(A.CHAPTER,A.initialChapter(A.CHAPTER),{type:'begin'});
storage.set(A.CHAPTER_KEY,A.serializeChapter(A.CHAPTER,chapter));
const chapterRaw=storage.get(A.CHAPTER_KEY);
await mount();
await click('进入雾灯工坊');
assert.deepEqual(JSON.parse(storage.get(A.CHAPTER_KEY)),JSON.parse(chapterRaw),'Existing chapter resumes without reset');
await click('← 场景选择');
await unmount();
console.log('Scene UI: fresh locks, deep links, legacy migration, direct resume/revisit, replay retention, browser Back and health lock passed.');
